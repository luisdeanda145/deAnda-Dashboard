/* Builds supabase/seed.sql from the app's starting data:
   the team, pillars and workstreams in src/data/board.js and the
   tasks imported from the spreadsheet in src/data/tasks.json.
   Run from the project folder:  node supabase/make-seed.mjs  */
import { readFileSync, writeFileSync } from 'node:fs'
import { DEFAULT_PILLARS, DEFAULT_TEAM, DEFAULT_WORKSTREAMS } from '../src/data/board.js'

const tasks = JSON.parse(readFileSync(new URL('../src/data/tasks.json', import.meta.url), 'utf8'))
const q = (v) => (v == null ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const rows = (list) => list.join(',\n')

const out = `-- ============================================================
-- Starting data: run once in Supabase → SQL Editor, after schema.sql.
-- Generated by supabase/make-seed.mjs — don't edit by hand.
-- Re-running is safe: existing rows are left as they are.
-- ============================================================

insert into public.team_members (name, role, sort) values
${rows(DEFAULT_TEAM.map((p, i) => `  (${q(p.name)}, ${q(p.role || null)}, ${i})`))}
on conflict (name) do nothing;

insert into public.pillars (name, code, tone, blurb, sort) values
${rows(DEFAULT_PILLARS.map((p, i) => `  (${q(p.name)}, ${q(p.code)}, ${q(p.tone)}, ${q(p.blurb || '')}, ${i})`))}
on conflict (name) do nothing;

insert into public.workstreams (name, pillar, sort) values
${rows(DEFAULT_WORKSTREAMS.map((w, i) => `  (${q(w.name)}, ${q(w.pillar)}, ${i})`))}
on conflict (pillar, name) do nothing;

insert into public.tasks (id, owner, title, pillar, workstream, priority, status, due, completed, points, hours, notes) values
${rows(tasks.map((t) => `  (${[t.id, t.owner, t.title, t.pillar, t.workstream, t.priority, t.status, t.due, t.completed, t.points, t.hours, t.notes].map(q).join(', ')})`))}
on conflict (id) do nothing;

-- the board's first month is November 2026
insert into public.board_meta (key, value) values ('first_month', '2026-11')
on conflict (key) do update set value = excluded.value;
`
writeFileSync(new URL('./seed.sql', import.meta.url), out)
console.log(`seed.sql: ${DEFAULT_TEAM.length} people, ${DEFAULT_PILLARS.length} pillars, ${DEFAULT_WORKSTREAMS.length} workstreams, ${tasks.length} tasks`)
